"""Validation of incoming records against a model's feature schema.

The feature schema is a JSON Schema (Draft 2020-12) document generated by the
trainer, extended with a few ``x-`` keys:

* ``x-feature-order``: the column order the model expects;
* ``x-kind``: ``number``, ``integer``, ``binary`` or ``categorical``;
* ``x-observed-range``: [min, max] seen during training (used for warnings);
* ``x-unit``: optional unit, for documentation.

Categorical values are encoded as their index in the ``enum`` list, so every
model receives a plain float matrix.
"""

from __future__ import annotations

import copy
import math
from dataclasses import dataclass
from typing import Any

import numpy as np
from jsonschema import Draft202012Validator


@dataclass(frozen=True)
class FieldError:
    field: str
    message: str


class FeatureValidator:
    def __init__(self, feature_schema: dict[str, Any], *, reject_unknown_fields: bool) -> None:
        schema = copy.deepcopy(feature_schema)
        schema["additionalProperties"] = not reject_unknown_fields
        Draft202012Validator.check_schema(schema)
        self._validator = Draft202012Validator(schema)
        self._properties: dict[str, dict[str, Any]] = schema["properties"]
        self.feature_order: list[str] = list(schema["x-feature-order"])

    def validate(self, features: Any) -> tuple[list[FieldError], list[str]]:
        """Return (errors, warnings) for one record's ``features`` object."""
        if not isinstance(features, dict):
            return [FieldError("features", "must be a JSON object")], []

        errors = [
            FieldError(_error_field(err), err.message)
            for err in sorted(self._validator.iter_errors(features), key=lambda e: list(e.path))
        ]
        # JSON Schema cannot express "finite"; Python's json module accepts NaN/Infinity.
        for name, value in features.items():
            if isinstance(value, float) and not math.isfinite(value):
                errors.append(FieldError(name, "must be a finite number (NaN and Infinity are not allowed)"))

        warnings: list[str] = []
        if not errors:
            for name in self.feature_order:
                observed = self._properties[name].get("x-observed-range")
                value = features[name]
                if observed and isinstance(value, (int, float)) and not (observed[0] <= value <= observed[1]):
                    warnings.append(
                        f"{name}={value} is outside the training range [{observed[0]}, {observed[1]}]; "
                        "the prediction may be unreliable"
                    )
        return errors, warnings

    def to_matrix(self, records: list[dict[str, Any]]) -> np.ndarray:
        """Convert already-validated feature objects to a float32 matrix."""
        matrix = np.empty((len(records), len(self.feature_order)), dtype=np.float32)
        for col, name in enumerate(self.feature_order):
            prop = self._properties[name]
            if prop.get("x-kind") == "categorical":
                codes = {value: index for index, value in enumerate(prop["enum"])}
                matrix[:, col] = [codes[r[name]] for r in records]
            else:
                matrix[:, col] = [r[name] for r in records]
        return matrix


def _error_field(err: Any) -> str:
    if err.validator == "required":
        return err.message.split("'")[1]
    if err.validator == "additionalProperties":
        return "features"
    return ".".join(str(p) for p in err.absolute_path) or "features"
